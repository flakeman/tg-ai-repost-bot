import json
import logging
import re
from typing import Optional, Tuple, List
from openai import AsyncOpenAI
from src.domain.interfaces import ILLMRewriter
from src.domain.models import Tone, PostContent
from src.infrastructure.ai.prompts import build_system_prompt, build_user_prompt
from src.infrastructure.ai.json_parser import RobustJsonParser

logger = logging.getLogger(__name__)


class RewriterError(Exception):
    """Raised when rewriting fails or output cannot be parsed."""
    pass


class OpenAIRewriter(ILLMRewriter):
    def __init__(
        self,
        api_key: str,
        model: str = "gpt-4o-mini",
        base_url: Optional[str] = None,
        client: Optional[AsyncOpenAI] = None,
        fallback_models: Optional[List[str]] = None,
    ):
        self.model = model
        self.fallback_models = fallback_models
        self.client = client or AsyncOpenAI(api_key=api_key, base_url=base_url)

    async def rewrite_with_prompt(
        self, raw_text: str, tone: Tone, title_hint: Optional[str] = None
    ) -> Tuple[PostContent, Optional[str]]:
        system_prompt = build_system_prompt(tone)
        user_prompt = build_user_prompt(raw_text, title_hint)

        candidate_models = [self.model]
        fallbacks = self.fallback_models or [
            "gpt-6-sol",
            "gpt-5.6-sol",
            "deepseek-v4.1-flash-1017",
            "claude-haiku-5-5",
            "qwen3.8-flash",
            "gpt-4o-mini",
        ]
        for m in fallbacks:
            if m not in candidate_models:
                candidate_models.append(m)

        content = ""
        last_error = None
        for model_to_try in candidate_models:
            try:
                logger.info("Attempting LLM rewrite with model %s...", model_to_try)
                response = await self.client.chat.completions.create(
                    model=model_to_try,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    temperature=0.7,
                    response_format={"type": "json_object"},
                )
                content = response.choices[0].message.content or ""
                if content:
                    if model_to_try != self.model:
                        logger.warning(
                            "Primary model %s failed, successfully rewrote post using fallback model %s",
                            self.model,
                            model_to_try,
                        )
                    break
            except Exception as exc:
                last_error = exc
                err_str = str(exc)
                logger.warning("LLM model %s failed: %s. Trying next candidate...", model_to_try, err_str[:200])
                if "invalid_api_key" in err_str or "Unauthorized" in err_str or "401" in err_str:
                    raise RewriterError(f"Authentication failed: {exc}") from exc
                continue

        if not content:
            raise RewriterError(f"LLM API error ({self.model}): {last_error}") from last_error

        parsed = self._parse_json_payload(content)
        title = parsed.get("title", "Без заголовка").strip()
        body = parsed.get("body", "").strip()
        hashtags = parsed.get("hashtags", [])
        if isinstance(hashtags, str):
            hashtags = [h.strip() for h in hashtags.split() if h.startswith("#")]
        image_prompt = parsed.get("image_prompt")
        image_prompts = parsed.get("image_prompts", [])
        if isinstance(image_prompts, str):
            image_prompts = [p.strip() for p in image_prompts.split("\n") if p.strip()]
        keywords = parsed.get("keywords", [])
        if isinstance(keywords, str):
            keywords = [k.strip() for k in keywords.split(",") if k.strip()]

        if not body:
            raise RewriterError("Empty body generated by LLM")

        draft = PostContent(
            title=title,
            body=body,
            hashtags=hashtags,
            image_prompts=image_prompts,
            keywords=keywords,
        )
        return draft, image_prompt

    async def rewrite(self, raw_text: str, tone: Tone, title_hint: Optional[str] = None) -> PostContent:
        draft, _ = await self.rewrite_with_prompt(raw_text, tone, title_hint)
        return draft

    @staticmethod
    def _parse_json_payload(raw_content: str) -> dict:
        try:
            return RobustJsonParser.parse(raw_content)
        except Exception as err:
            raise RewriterError(f"Failed to parse LLM JSON response: {err}\nContent was: {raw_content[:200]}")


class DeepSeekRewriter(OpenAIRewriter):
    def __init__(
        self,
        api_key: str,
        model: str = "deepseek-chat",
        base_url: str = "https://api.deepseek.com",
        client: Optional[AsyncOpenAI] = None,
    ):
        super().__init__(api_key=api_key, model=model, base_url=base_url, client=client)
